SYNTHETIC_NOTE = "SYNTHETIC FIXTURE — generated by amperes.fixtures; not customer or physical-robot data"
BASE_T = 1_790_000_000.0  # arbitrary fixed epoch (2026-09) so fixtures are deterministic

# defect type -> (rules expected to fire, expected status, detectable by design)
DEFECTS = {
    "missing_observations_gap": ({"T003_time_gap"}, "suspicious", True),
    "missing_values_null": ({"C007_missing_samples"}, "invalid_data", True),
    "non_monotonic_timestamps": ({"T001_non_monotonic"}, "invalid_data", True),
    "duplicate_timestamps": ({"T002_duplicate_timestamps"}, "suspicious", True),
    "nan_values": ({"S001_non_finite"}, "invalid_data", True),
    "out_of_range": ({"S002_out_of_range"}, "suspicious", True),
    "truncated_episode": ({"C004_truncated"}, "suspicious", True),
    "label_flip_with_state": ({"O002_label_contradicts_state"}, "invalid_data", True),
    "label_flip_without_state": ({"O002_label_contradicts_state"}, "suspicious", False),
    "duplicate_record": ({"D001_duplicate_content"}, "suspicious", True),
    "duplicate_source_id": ({"D002_duplicate_source_id"}, "suspicious", True),
    "stale_signal": ({"S004_stale_signal"}, "suspicious", True),
    "action_misalignment": ({"T005_obs_action_misalignment"}, "suspicious", True),
    "action_spike": ({"S003_action_discontinuity"}, "suspicious", True),
    "missing_outcome": ({"C005_missing_outcome"}, "suspicious", True),
    "missing_channel": ({"C008_missing_channel"}, "suspicious", True),
}
PER_DEFECT = 4
N_CLEAN_SUCCESS = 16
N_CLEAN_FAILURE = 16


def _base_episodes(work: Path, n: int) -> list[Episode]:
    conds = V.sample(n * 3, "fixture", master_seed=777_000)
    conds = [V.make_condition({**c["changed"], "obs_noise_std": max(0.002, c["env_params"]["obs_noise_std"])}, c["seed"],
                              "fixture", "fixture", "fixture base " + c["description"]) for c in conds]
    specs = [{"run_id": "fixture_base", "episode_id": f"fx{i:04d}", "condition": c, "policy_config": ScriptedConfig().model_dump(),
              "artifacts_dir": str(work)} for i, c in enumerate(conds)]
    res = run_batch(specs, workers=1)
    return [read_episode(Path(r["artifact"])) for r in res if r["outcome"] in ("success", "failure", "timeout")]


def _export(ep: Episode, i: int, session: str, keep_replay: bool) -> Episode:
    """Turn a simulator episode into what a customer export might look like (unix time, source labels)."""
    e = ep.model_copy(deep=True)
    start = BASE_T + i * 20.0
    for s in e.streams.values():
        s.t = [round(start + t, 6) for t in s.t]
    e.start_time = start
    e.end_time = max(s.t[-1] for s in e.streams.values())
    e.time_base = "unix_s"
    e.events = [ev for ev in e.events if ev.type != "policy_phase"]
    for ev in e.events:
        ev.t = None if ev.t is None else round(start + ev.t, 6)
    e.episode_id = f"rec-{i:05d}"
    e.source.dataset_id = "fixture"
    e.source.adapter = "fixture"
    e.source.source_record_id = e.episode_id
    e.source.synthetic = True
    e.source.synthetic_note = SYNTHETIC_NOTE
    e.session = SessionInfo(session_id=session, workcell_id="wc-sim", operator_id="op-fixture")
    e.robot = RobotInfo(embodiment="mujoco-gantry", device_id="sim-01", config_id="baseline")
    e.streams["obs.object_pos_est"].source = "sim:object_pos_est;max_unchanged_s=0.5"
    label = ep.outcome.label
    e.outcome = Outcome(label=label, provenance="source_label", verified=False)
    e.diagnosis = None
    e.extra = {"fixture": True}
    if not keep_replay:
        e.replay = None
        for k in [k for k in e.streams if k.startswith("state.")]:
            del e.streams[k]
    return e


def _inject(e: Episode, defect: str, rng: np.random.Generator, pool: list[Episode]) -> list[Episode]:
    obs = [k for k, s in e.streams.items() if s.kind == "observation"]
    n = len(e.streams["obs.tcp_pos"].t)
    if defect == "missing_observations_gap":
        a, b = int(n * 0.4), int(n * 0.55)
        for k in obs:
            s = e.streams[k]
            s.t, s.values = s.t[:a] + s.t[b:], s.values[:a] + s.values[b:]
    elif defect == "missing_values_null":
        s = e.streams["obs.tcp_pos"]
        for j in range(int(n * 0.3), int(n * 0.3) + max(5, int(n * 0.25))):
            s.values[j] = [None] * len(s.values[j])
    elif defect == "non_monotonic_timestamps":
        s = e.streams["obs.tcp_pos"]
        j = n // 2
        s.t[j], s.t[j + 1] = s.t[j + 1], s.t[j]
    elif defect == "duplicate_timestamps":
        s = e.streams["obs.finger_gap"]
        for j in (n // 3, n // 2):
            s.t[j + 1] = s.t[j]
    elif defect == "nan_values":
        s = e.streams["obs.object_pos_est"]
        for j in rng.choice(n, 5, replace=False):
            s.values[int(j)][0] = float("nan")
    elif defect == "out_of_range":
        e.streams["obs.finger_gap"].values[n // 2] = [0.5]
    elif defect == "truncated_episode":
        cut = int(n * 0.4)
        for s in e.streams.values():
            k = min(cut, len(s.t))
            s.t, s.values = s.t[:k], s.values[:k]
    elif defect == "label_flip_with_state" or defect == "label_flip_without_state":
        e.outcome.label = "failure" if e.outcome.label == "success" else "success"
    elif defect == "duplicate_record":
        d = e.model_copy(deep=True)
        d.episode_id = e.episode_id + "-dup"
        d.source.source_record_id = d.episode_id
        return [e, d]
    elif defect == "duplicate_source_id":
        other = pool.pop()
        other.source.source_record_id = e.source.source_record_id
        return [e, other]
    elif defect == "stale_signal":
        s = e.streams["obs.object_pos_est"]
        j = int(n * 0.3)
        for k in range(j, min(n, j + 100)):
            s.values[k] = list(s.values[j])
    elif defect == "action_misalignment":
        a = e.streams["act.command"]
        a.t = [round(t + 0.008, 6) for t in a.t]
    elif defect == "action_spike":
        a = e.streams["act.command"]
        j = len(a.t) // 2
        a.values[j] = [1.0, -1.0, 1.0, a.values[j][3]]
        a.values[j + 1] = [-1.0, 1.0, -1.0, a.values[j + 1][3]]
    elif defect == "missing_outcome":
        e.outcome = None
    elif defect == "missing_channel":
        del e.streams["obs.finger_gap"]
    return [e]


def defect_corpus(out_dir: Path, work_dir: Path) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(42)
    need = len(DEFECTS) * PER_DEFECT + N_CLEAN_SUCCESS + N_CLEAN_FAILURE + PER_DEFECT + 10
    base = _base_episodes(work_dir, need)
    succ = [b for b in base if b.outcome.label == "success"]
    fail = [b for b in base if b.outcome.label != "success"]
    episodes, labels = [], {}
    i = 0

    def take(pref_fail: bool):
        src = fail if pref_fail and fail else succ if succ else fail
        return src.pop(0)

    for _ in range(N_CLEAN_SUCCESS):
        e = _export(take(False), i, f"sess-{i // 20:02d}", keep_replay=True)
        i += 1
        episodes.append(e)
        labels[e.episode_id] = {"defects": [], "expected_rules": [], "expected_status": "verified_success", "detectable": True}
    for _ in range(N_CLEAN_FAILURE):
        e = _export(take(True), i, f"sess-{i // 20:02d}", keep_replay=True)
        i += 1
        episodes.append(e)
        labels[e.episode_id] = {"defects": [], "expected_rules": [], "expected_status": "valid_failed_task", "detectable": True}
    spare = []
    for d, (rules, status, detectable) in DEFECTS.items():
        for k in range(PER_DEFECT):
            keep = d != "label_flip_without_state"
            e = _export(take(k % 2 == 1), i, f"sess-{i // 20:02d}", keep_replay=keep)
            i += 1
            if d == "duplicate_source_id" and not spare:
                spare = [_export(take(False), 10_000 + j, "sess-spare", True) for j in range(PER_DEFECT)]
            for x in _inject(e, d, rng, spare):
                episodes.append(x)
                is_primary = x.episode_id == e.episode_id
                if d == "duplicate_record" and is_primary:
                    labels[x.episode_id] = {"defects": [], "expected_rules": [], "expected_status": None,
                                            "detectable": True, "note": "original of a duplicate pair; not itself defective"}
                elif d == "duplicate_source_id" and is_primary:
                    labels[x.episode_id] = {"defects": [], "expected_rules": [], "expected_status": None, "detectable": True,
                                            "note": "first holder of a reused source id; not itself defective"}
                else:
                    labels[x.episode_id] = {"defects": [d], "expected_rules": sorted(rules), "expected_status": status,
                                            "detectable": detectable,
                                            # removing the state streams is itself a real, detectable difference
                                            "secondary_rules": ["C008_missing_channel"] if d == "label_flip_without_state" else []}
    with open(out_dir / "episodes.jsonl", "w") as fh:
        for e in episodes:
            fh.write(episode_to_json(e) + "\n")
    (out_dir / "labels.json").write_text(json.dumps({"note": SYNTHETIC_NOTE, "labels": labels}, indent=1))
    (out_dir / "README.txt").write_text(SYNTHETIC_NOTE + "\nDetectors must not read labels.json.\n")
    return {"n_episodes": len(episodes), "n_labelled_defective": sum(1 for v in labels.values() if v["defects"]),
            "path": str(out_dir)}


