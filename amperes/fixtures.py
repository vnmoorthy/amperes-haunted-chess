def ops_package(out_dir: Path, seed: int = 7) -> dict[str, Any]:
    """Fictional 3-workcell program, 4 days x 2 sessions/day/workcell, ~20 episodes/session (SYNTHETIC)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    wcs = {"wc-A": "arm-01", "wc-B": "arm-02", "wc-C": "arm-03"}
    day = 86_400.0
    episodes, tele, events = [], [], []
    ev_n = 0
    truth = {"note": SYNTHETIC_NOTE, "planted": [
        {"id": "P1", "pattern": "wc-B switches cfg-v1 -> cfg-v2 at day 2 08:00; afterwards ~35% of episodes lose observations in their final segment, CAM_FRAME_DROP events (data_recording_failure) appear, and cycle time rises ~25%",
         "expect": ["B004_cycle_time_after_change", "B003_config_fault_association", "B002_session_missing_observations",
                    "incident dq:C004_truncated", "incident of:data_recording_failure:CAM_FRAME_DROP"]},
        {"id": "P2", "pattern": "wc-A GRIPPER_OVERCURRENT (hardware_fault) in several sessions; incident INC-7 acknowledged and resolved on day 2; recurs on day 3",
         "expect": ["repeat_failure_after_resolution", "incident of:hardware_fault:GRIPPER_OVERCURRENT"]},
        {"id": "P3", "pattern": "wc-C has no station availability events -> availability must be not_computable",
         "expect": ["availability wc-C not_computable"]},
        {"id": "P4", "pattern": "~15% failed grasps with valid data -> valid_failed_task, still usable", "expect": ["valid_failed_task > 0"]},
        {"id": "P5", "pattern": "wc-C day 3 session 1: outcome labels missing for 8 episodes", "expect": ["C005_missing_outcome"]},
        {"id": "P6", "pattern": "every GRIPPER_OVERCURRENT fault row (8) exported twice (identical content)",
         "expect": ["duplicate_events_dropped == 8"]},
    ]}

    def ev(t, wc, et, sid=None, cls="", code="", msg="", ep="", inc="", t_end=""):
        nonlocal ev_n
        ev_n += 1
        events.append({"event_id": "", "timestamp": f"{t:.3f}", "end_timestamp": t_end, "workcell_id": wc, "device_id": wcs[wc],
                       "session_id": sid or "", "episode_id": ep, "event_type": et, "event_class": cls, "code": code,
                       "message": msg, "incident_ref": inc})

    dup_faults = []
    ep_i = 0
    for d in range(4):
        for wc in wcs:
            cfg = "cfg-v2" if (wc == "wc-B" and d >= 1) else "cfg-v1"
            if wc == "wc-B" and d == 1:
                ev(BASE_T + d * day + 8 * 3600 - 600, wc, "config_change", code="cfg-v1->cfg-v2", msg="camera driver update")
            for s in range(2):
                sid = f"{wc}-d{d + 1}-s{s + 1}"
                t = BASE_T + d * day + (8 + 5 * s) * 3600
                ev(t, wc, "session_start", sid)
                if wc != "wc-C":
                    ev(t + 1, wc, "station_up", sid)
                attempt = 1
                for k in range(20):
                    dur = float(rng.normal(30, 3)) * (1.25 if cfg == "cfg-v2" else 1.0)
                    st = t + 60 + k * 50.0
                    en = st + dur
                    fail = rng.random() < 0.15
                    drop = cfg == "cfg-v2" and rng.random() < 0.35
                    missing_label = wc == "wc-C" and d == 2 and s == 0 and k < 8
                    eid = f"{sid}-e{k:02d}"
                    episodes.append({"episode_id": eid, "task_id": "pick_place_bin", "task_version": "2.1",
                                     "policy_id": "teleop" if d < 2 else "vla-collect", "policy_version": "n/a" if d < 2 else "0.4.1",
                                     "embodiment": "6dof-arm", "device_id": wcs[wc], "config_id": cfg, "session_id": sid,
                                     "workcell_id": wc, "operator_id": f"op-{(d + s) % 3 + 1}", "start_time": f"{st:.3f}",
                                     "end_time": f"{en:.3f}", "outcome_label": "" if missing_label else ("failure" if fail else "success"),
                                     "outcome_provenance": "" if missing_label else "operator", "outcome_reason": "grasp_missed" if fail else "",
                                     "attempt_index": attempt})
                    attempt = attempt + 1 if fail else 1
                    n = int(dur * 10)
                    stop = int(n * 0.6) if drop else n
                    for j in range(n + 1):
                        tt = st + j * 0.1
                        q = [round(math.sin(0.3 * tt + p) * 1.2 + rng.normal(0, 0.002), 5) for p in range(6)]
                        if j <= stop:
                            tele.append([eid, f"{tt:.3f}", "obs.joint_pos", *q])
                            tele.append([eid, f"{tt:.3f}", "obs.gripper", round(0.04 + 0.04 * math.cos(tt), 5), *[""] * 5])
                        tele.append([eid, f"{tt:.3f}", "act.joint_cmd", *[round(v + 0.01, 5) for v in q]])
                    if drop:
                        ev(st + dur * 0.6, wc, "recording_error", sid, "data_recording_failure", "CAM_FRAME_DROP", "frame queue overflow", eid)
                    if wc == "wc-A" and k in (5, 14) and d in (0, 2):
                        inc = "INC-7"
                        ev(st + 5, wc, "fault", sid, "hardware_fault", "GRIPPER_OVERCURRENT", "gripper motor current limit", eid, inc)
                        dup_faults.append(events[-1])
                        ev(st + 5 + 180, wc, "recovery", sid, code="GRIPPER_OVERCURRENT", msg="power-cycled gripper", ep=eid, inc=inc)
                        ev(st + 6, wc, "station_down", sid)
                        ev(st + 6 + 180, wc, "station_up", sid)
                    if wc == "wc-C" and k == 10:
                        ev(st + 3, wc, "manual_intervention", sid, "operator_interruption", "OBJ_RESET", "operator repositioned bin", eid)
                ev(t + 60 + 20 * 50 + 60, wc, "session_end", sid)
        if d == 1:
            first_fault = next(e for e in events if e["code"] == "GRIPPER_OVERCURRENT")
            ev(float(first_fault["timestamp"]) + 3600, "wc-A", "incident_ack", inc="INC-7", msg="acknowledged by on-call")
            ev(BASE_T + d * day + 20 * 3600, "wc-A", "incident_resolved", inc="INC-7", msg="replaced gripper cable")
    events += [dict(e) for e in dup_faults[:12]]
    events.sort(key=lambda e: float(e["timestamp"]))
    with open(out_dir / "episodes.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(episodes[0]))
        w.writeheader()
        w.writerows(episodes)
    with open(out_dir / "telemetry.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["episode_id", "timestamp", "stream", "v0", "v1", "v2", "v3", "v4", "v5"])
        w.writerows(tele)
    with open(out_dir / "streams.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["stream", "kind", "units", "expected_rate_hz", "valid_low", "valid_high", "max_unchanged_s"])
        w.writerow(["obs.joint_pos", "observation", "rad", 10, -3.2, 3.2, ""])
        w.writerow(["obs.gripper", "observation", "m", 10, 0, 0.09, ""])
        w.writerow(["act.joint_cmd", "action", "rad", 10, -3.2, 3.2, ""])
    from amperes.ops import EVENT_COLUMNS

    with open(out_dir / "events.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=EVENT_COLUMNS)
        w.writeheader()
        w.writerows(events)
    (out_dir / "planted_truth.json").write_text(json.dumps(truth, indent=1))
    (out_dir / "README.txt").write_text(SYNTHETIC_NOTE + "\nA fictional collection program used to demonstrate the workflow.\n")
    return {"episodes": len(episodes), "telemetry_rows": len(tele), "events": len(events), "path": str(out_dir)}
